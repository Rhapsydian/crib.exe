/**
 * Generates src/engine/crib-table.ts: the average crib a two-card throw
 * makes (milestone 4, the user's call -- for the coach and the AI).
 *
 * For each throw -- two ranks, and whether the two cards share a suit
 * (only a five-card flush scores in the crib, so suits matter a little)
 * -- the crib is averaged over every possible pair of other crib cards
 * and every cut from the rest of the deck, counted exactly (countCrib).
 * It assumes the other two crib cards are random; a real opponent
 * throws deliberately, so this is a first model, not the last word.
 *
 * Usage:
 *   npx tsx scripts/crib-table.ts            # writes src/engine/crib-table.ts
 */
import { writeFileSync } from 'node:fs';
import { createDeck } from '../src/engine/deck';
import { cardsEqual, type Card, type Rank, type Suit } from '../src/engine/cards';
import { countCrib } from '../src/engine/scoring';

const deck = createDeck();

/** The average crib for throwing `a` and `b`, exactly. */
function averageCrib(a: Card, b: Card): number {
  const rest = deck.filter((c) => !cardsEqual(c, a) && !cardsEqual(c, b));
  let total = 0;
  let n = 0;
  for (let i = 0; i < rest.length; i++) {
    for (let j = i + 1; j < rest.length; j++) {
      const crib = [a, b, rest[i], rest[j]];
      for (let k = 0; k < rest.length; k++) {
        if (k === i || k === j) continue;
        total += countCrib(crib, rest[k]).total;
        n++;
      }
    }
  }
  return total / n;
}

const entries: string[] = [];
const started = Date.now();
for (let lo = 1; lo <= 13; lo++) {
  for (let hi = lo; hi <= 13; hi++) {
    // Off-suit (a pair is always off-suit); and suited, for two ranks.
    const off = averageCrib({ rank: lo as Rank, suit: 0 as Suit }, { rank: hi as Rank, suit: 1 as Suit });
    entries.push(`  '${lo}-${hi}': ${off.toFixed(3)},`);
    if (lo !== hi) {
      const suited = averageCrib({ rank: lo as Rank, suit: 0 as Suit }, { rank: hi as Rank, suit: 0 as Suit });
      entries.push(`  '${lo}-${hi}s': ${suited.toFixed(3)},`);
    }
  }
  console.log(`rank ${lo} done (${((Date.now() - started) / 1000).toFixed(0)}s)`);
}

const file = `// GENERATED by scripts/crib-table.ts -- do not edit by hand.
/**
 * The average crib a two-card throw makes (milestone 4): keyed
 * 'low-high' by rank (A = 1 ... K = 13), with an 's' suffix when the two
 * cards share a suit. Averaged over every pair of other crib cards and
 * every cut, counted exactly; the other two crib cards are taken as
 * random. Used by the AI's discards (ai.ts's cribExpectedValue) and the
 * coach.
 */
export const CRIB_TABLE: Readonly<Record<string, number>> = {
${entries.join('\n')}
};
`;
writeFileSync(new URL('../src/engine/crib-table.ts', import.meta.url), file);
console.log(`wrote ${entries.length} entries`);
